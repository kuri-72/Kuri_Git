/**
 * x72_port.h — 板级适配（STM32F103C8T6 + 江科大标准库工程）
 * ==========================================================
 * 这个头文件集中放"和你硬件有关"的开关。换板子/换引脚只改这里。
 */
#ifndef X72_PORT_H
#define X72_PORT_H

#include "stm32f10x.h"

/* ================================================================
 *  功能开关
 * ================================================================ */
#define X72_USE_OLED  1     /* OLED 已接：PB8=SCL, PB9=SDA（软件 I2C） */
#define X72_USE_KEY   0     /* 按键没带：先关。回家改 1 并填 main.c 的预留位置 */

/* ================================================================
 *  PWM 参数（v0.3：100 级 → 1000 级）
 * ================================================================
 *  硬件配置（PWM.c 里同步改过）：
 *      TIM_Prescaler = 72 - 1     → 72MHz / 72 = 1MHz 计数时钟
 *      TIM_Period    = 1000       → 1MHz / 1000 = 1kHz 更新（1ms 中断）
 *      CCR 范围      = 0..1000    → 1000 级分辨率
 *
 *  为什么提分辨率：
 *      100 级时呼吸每步跨 1%，慢呼吸能看出台阶；1000 级每步 0.1%，肉眼看不出。
 *      代价是 Flash/CPU 略增（可忽略），PWM 频率不变。
 *
 *  ⚠ 这一处和 PWM.c 的 TIM_Period/TIM_Prescaler 必须成对改，
 *    只改一边会导致"亮度满不了"或"节拍不再是 1ms"。
 */
#define X72_PWM_MAX   1000

/* ================================================================
 *  毫秒计时来源
 * ================================================================
 *  必须用 TIM2 更新中断，不能用 SysTick ——
 *  你的 Delay_us() 直接改写 SysTick->LOAD 并轮询，会把 SysTick 抢走。
 */
void     x72_tick_inc(void);

/* 板级初始化（在 main 里调一次） */
void     x72_board_init(void);

/* ================================================================
 *  串口：USART1 / PA9(TX) / PA10(RX) / 115200 8N1
 * ================================================================
 *  没用 USB-TTL 也可以先初始化：TX 会往外发，但没人接，无害。
 */
#define X72_UART_BAUD   115200
#define X72_RX_BUF_SIZE 64      /* 环形缓冲，必须 2 的幂 */

void     USART1_Init(uint32_t baud);
uint8_t  x72_rx_take(uint8_t *byte);   /* 有数据返回 1 并写入 *byte */
uint16_t x72_rx_count(void);           /* 累计收到的字节数（调试用） */
uint8_t  x72_rx_overflow(void);        /* 是否发生过溢出（丢过字节） */

#endif /* X72_PORT_H */
