/**
 * x72_port.c — 板级适配实现（STM32F103C8T6 / 标准库）
 * =====================================================
 * 只做三件事：
 *   1) 提供 x72_tick_ms() 的毫秒来源（TIM2 中断计数）
 *   2) 把内部亮度 0..1000 写进 PWM（调用你工程里已有的 PWM_SetCompare1）
 *   3) 错误上报（空实现，避免在中断里做串口打印）
 *
 * ⚠ 这里**没有**任何中断服务函数，中断都在 stm32f10x_it.c 里。
 */
#include "x72_port.h"
#include "x72_proto.h"
#include "PWM.h"

/* ================================================================
 *  1) 毫秒计时：TIM2 更新中断里自增
 * ================================================================
 *  TIM2 = 72MHz / 72 / 1000 = 1kHz 更新事件 → 正好 1ms 一次。
 *  （v0.3 调整：预分频 720→72、周期 100→1000，频率不变、分辨率 ×10）
 */
static volatile uint32_t s_ms = 0;

void x72_tick_inc(void)
{
    s_ms++;
}

uint32_t x72_tick_ms(void)
{
    return s_ms;
}

/* ================================================================
 *  2) 亮度 → PWM
 * ================================================================
 *  入参是内部刻度 0..1000，直接映射到 CCR 0..X72_PWM_MAX（也是 1000）。
 *
 *  变量改名说明：v0.2 以前参数叫 percent（0..100），
 *  v0.3 起叫 level（0..1000）。类型也改成 uint16_t。
 */
void x72_led_write(uint16_t level)
{
    uint16_t ccr;

    if (level > (uint16_t)X72_BRIGHT_IN_MAX) level = (uint16_t)X72_BRIGHT_IN_MAX;

    /* X72_PWM_MAX 和 X72_BRIGHT_IN_MAX 现在都是 1000，
       这里仍然做一次换算，方便以后单独调其中一个。 */
    ccr = (uint16_t)((uint32_t)level * X72_PWM_MAX / X72_BRIGHT_IN_MAX);

    PWM_SetCompare1(ccr);
}

/* ================================================================
 *  3) 错误上报（空实现）
 * ================================================================
 *  第一版故意不做串口打印：x72_on_error 可能在解析失败时被调用，
 *  如果在里面阻塞发串口，会拖慢主循环。要调试就去看 OLED 的 E 计数。
 */
void x72_on_error(x72_status_t err)
{
    (void)err;
}

/* ================================================================
 *  板级初始化
 * ================================================================ */
void x72_board_init(void)
{
    /* 目前没有需要在这里做的事：
       - PWM 由你原来的 PWM_Init() 负责（含 TIM2 中断使能）
       - 串口由 USART1_Init() 负责
       - OLED 由 OLED_Init() 负责
       留这个函数是为了将来加东西时有个统一入口。 */
}
